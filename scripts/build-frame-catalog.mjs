// Builds the token-frame catalog (C5a) from the palette and preset JSON under
// packages/shared/src/frames/, and renders its contact sheet:
//
//   packages/shared/src/frames/frameCatalog.generated.ts   the typed catalog both apps read
//   docs/frames/contact-sheet.png                          every preset at skinny, regular and
//                                                          slab on dark and light, the 128 tier
//   docs/frames/contact-sheet.md                           what each row and column of it is
//
// Everything is checked first (shared/src/frames/catalogSource.ts): a palette
// missing a role, a colour that is not #rrggbb or "personal", a preset over the
// weight cap, an unknown generator, palette or param, or a param out of range is
// refused with its reason, and nothing is written. The sheet is drawn by the
// same pure bake the table uses, encoded to PNG here with node:zlib (no canvas,
// no native dependency). The TypeScript sources load through the server's tsx.
//
// Usage:
//   node scripts/build-frame-catalog.mjs              check, write the catalog, render the sheet
//   node scripts/build-frame-catalog.mjs --check      check and report drift; write nothing (exit 1)
//   node scripts/build-frame-catalog.mjs --source <dir>   read palettes/ and presets/ from <dir>

import { createRequire } from "node:module";
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { deflateSync } from "node:zlib";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FRAMES = join(REPO, "packages", "shared", "src", "frames");
const CATALOG_FILE = join(FRAMES, "frameCatalog.generated.ts");
const SHEET_DIR = join(REPO, "docs", "frames");
const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const sourceAt = args.indexOf("--source");
const SOURCE = sourceAt >= 0 ? resolve(args[sourceAt + 1] ?? ".") : FRAMES;

const requireFromServer = createRequire(join(REPO, "apps", "server", "package.json"));
const { register } = await import(pathToFileURL(requireFromServer.resolve("tsx/esm/api")).href);
register();
const load = (relative) => import(pathToFileURL(join(FRAMES, relative)).href);

function readJsonDir(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => {
      try {
        return JSON.parse(readFileSync(join(dir, name), "utf8"));
      } catch (error) {
        return { id: `${name} (unreadable JSON: ${error.message})` };
      }
    });
}

const { buildFrameCatalogSource } = await load("catalogSource.ts");
const catalog = buildFrameCatalogSource(
  readJsonDir(join(SOURCE, "palettes")),
  readJsonDir(join(SOURCE, "presets")),
);
if (catalog.errors.length > 0) {
  console.error(`build-frame-catalog: refused (${catalog.errors.length})`);
  for (const error of catalog.errors) console.error(`  - ${error}`);
  process.exit(1);
}

const prettier = await import("prettier");
// One entry per line (prettier-ignore): the catalog grows by JSON, and one
// object per line keeps the generated file short and its diffs readable.
const entries = (list) => list.map((line) => `  ${line},`).join("\n");
const source = `// GENERATED by scripts/build-frame-catalog.mjs: do not edit. Edit the JSON
// under frames/palettes and frames/presets, then run the script.

import type { FramePalette, FramePreset } from "./types.js";

// prettier-ignore
export const FRAME_PALETTES: Readonly<Record<string, FramePalette>> = {
${entries(Object.values(catalog.palettes).map((palette) => `${JSON.stringify(palette.id)}: ${JSON.stringify(palette)}`))}
};

// prettier-ignore
export const FRAME_PRESETS: readonly FramePreset[] = [
${entries(catalog.presets.map((preset) => JSON.stringify(preset)))}
];
`;
const formatted = await prettier.format(source, {
  ...(await prettier.resolveConfig(CATALOG_FILE)),
  filepath: CATALOG_FILE,
});
const current = existsSync(CATALOG_FILE) ? readFileSync(CATALOG_FILE, "utf8") : "";
if (checkOnly) {
  if (current !== formatted) {
    console.error("build-frame-catalog: frameCatalog.generated.ts is out of date; run the script");
    process.exit(1);
  }
  console.log(
    `build-frame-catalog: ok (${Object.keys(catalog.palettes).length} palettes, ${catalog.presets.length} presets)`,
  );
  process.exit(0);
}
if (sourceAt >= 0) {
  console.log("build-frame-catalog: --source checked only; the shipped catalog is untouched");
  process.exit(0);
}
writeFileSync(CATALOG_FILE, formatted);

// --- The contact sheet ------------------------------------------------------

const { bakeFrame, presetFrame, FRAME_WEIGHTS } = await load("index.ts");
const TIER = 128;
const PAD = 8;
const CELL = TIER + PAD * 2;
const BACKGROUNDS = [
  ["dark map", [0x2a, 0x26, 0x22]],
  ["light map", [0xd8, 0xcf, 0xbd]],
];
const WEIGHTS = [
  ["skinny", FRAME_WEIGHTS.skinny],
  ["regular", FRAME_WEIGHTS.regular],
  ["slab", FRAME_WEIGHTS.slab],
];
const DEMO_ACCENT = "#4f7cc4";
// The darkest colours the C1 window allows, on the default ring: they must read by light.
const DARK_ROWS = [
  ["plain.ring", "#390076", "the colour window's darkest violet"],
  ["plain.ring", "#14254a", "a dark navy"],
  ["plain.ring", "#4a0f1c", "a dark maroon"],
];
const rows = [
  ...catalog.presets.map((preset) => [preset.id, DEMO_ACCENT, preset.name]),
  ...DARK_ROWS,
];
const width = CELL * WEIGHTS.length * BACKGROUNDS.length;
const height = CELL * rows.length;
const image = new Uint8Array(width * height * 4);
const started = performance.now();

rows.forEach(([presetId, accent], row) => {
  BACKGROUNDS.forEach(([, background], bgIndex) => {
    WEIGHTS.forEach(([, weight], weightIndex) => {
      const left = (bgIndex * WEIGHTS.length + weightIndex) * CELL;
      const top = row * CELL;
      const frame = presetFrame(presetId, weight);
      const baked = bakeFrame({
        frame,
        accent,
        seed: 0x1234 + row,
        tier: TIER,
        palettes: catalog.palettes,
      });
      // The picture stand-in: a muted disc filling the window, as a token's art would.
      const { window, extent } = baked.layout;
      for (let y = 0; y < CELL; y += 1) {
        for (let x = 0; x < CELL; x += 1) {
          const at = ((top + y) * width + left + x) * 4;
          let [r, g, b] = background;
          const fx = x - PAD;
          const fy = y - PAD;
          const tx = ((fx + 0.5) / TIER) * 2 * extent - extent;
          const ty = ((fy + 0.5) / TIER) * 2 * extent - extent;
          if (Math.hypot(tx, ty) < window) [r, g, b] = [0x5a, 0x63, 0x70];
          if (fx >= 0 && fy >= 0 && fx < TIER && fy < TIER) {
            const src = (fy * TIER + fx) * 4;
            const alpha = baked.pixels[src + 3] / 255;
            r = baked.pixels[src] * alpha + r * (1 - alpha);
            g = baked.pixels[src + 1] * alpha + g * (1 - alpha);
            b = baked.pixels[src + 2] * alpha + b * (1 - alpha);
          }
          image[at] = r;
          image[at + 1] = g;
          image[at + 2] = b;
          image[at + 3] = 255;
        }
      }
    });
  });
});
const elapsed = performance.now() - started;

function crc32(bytes) {
  let crc = ~0;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return ~crc >>> 0;
}
function chunk(type, data) {
  const out = Buffer.alloc(12 + data.length);
  out.writeUInt32BE(data.length, 0);
  out.write(type, 4, "ascii");
  Buffer.from(data).copy(out, 8);
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length);
  return out;
}
const header = Buffer.alloc(13);
header.writeUInt32BE(width, 0);
header.writeUInt32BE(height, 4);
header.set([8, 6, 0, 0, 0], 8); // 8-bit RGBA, no interlace
const raw = Buffer.alloc((width * 4 + 1) * height);
for (let y = 0; y < height; y += 1) {
  raw[y * (width * 4 + 1)] = 0;
  Buffer.from(image.buffer, y * width * 4, width * 4).copy(raw, y * (width * 4 + 1) + 1);
}
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk("IHDR", header),
  chunk("IDAT", deflateSync(raw, { level: 9 })),
  chunk("IEND", Buffer.alloc(0)),
]);
mkdirSync(SHEET_DIR, { recursive: true });
writeFileSync(join(SHEET_DIR, "contact-sheet.png"), png);

const columns = BACKGROUNDS.flatMap(([background]) =>
  WEIGHTS.map(([name, weight]) => `${name} (${weight}) on the ${background}`),
);
const legend = `# Token frame contact sheet

Generated by \`node scripts/build-frame-catalog.mjs\` with the catalog; do not edit.
Every frame is baked by the same pure bake the table uses, at the ${TIER} px tier, round a
grey stand-in for the token's picture.

Columns, left to right: ${columns.join("; ")}.

Rows, top to bottom (accent ${DEMO_ACCENT} where a preset takes the player's colour):

${rows.map(([id, accent, name], index) => `${index + 1}. \`${id}\`: ${name}${accent === DEMO_ACCENT ? "" : ` (${accent})`}`).join("\n")}
`;
writeFileSync(join(SHEET_DIR, "contact-sheet.md"), legend);
console.log(
  `build-frame-catalog: wrote the catalog (${Object.keys(catalog.palettes).length} palettes, ` +
    `${catalog.presets.length} presets) and the contact sheet (${rows.length * 6} bakes in ${elapsed.toFixed(0)} ms)`,
);
